#!/usr/bin/env python3
"""Build the project footprint library radio.pretty.

TI_DLA0010A_VSON-HR-10_2x3mm_P0.5mm: generated here from TI's land pattern for package DLA0010A
(TPS63802 datasheet SLVSEU9D, "EXAMPLE BOARD LAYOUT" 4223750/D, PDF p36), top view, mm, origin = package centre:
  pins 1-5 (left):   pad 0.60 x 0.25, centre x = -0.90, y = -1.0 .. +1.0 step 0.5 (pin 1 top)
  pins 6,7,9,10:     pad 0.90 x 0.25, centre x = +0.75 (pin 10 top, pin 6 bottom)
  pin 8 (GND):       pad 1.30 x 0.25, centre x = +0.55, y = 0
  corner radius 0.05 (R0.05 TYP), non-solder-mask-defined (preferred), 0.07 mm mask expansion max.
Cross-checked against the package outline (p35): body 2.0 x 3.0, left leads 0.3-0.5 long, right leads 0.6-0.8,
pin 8 lead 1.0-1.2: every land covers its lead and extends 0.2 mm beyond the body edge.
Independent check against the LCSC/EasyEDA footprint for C2845237 (easyeda2kicad): same pin numbering and the same
relative pad positions (0.00 mm after aligning origins); it uses 0.30 mm tall pads instead of TI's 0.25 and puts its
origin at the pad-bounding-box centre, 0.075 mm off the package centre. (A first read of the raw coordinates
mistook that origin shift for misplaced pads.) TI's pattern is used. The JLC placement preview must confirm the origin/rotation before ordering.

ESP32-C3-MINI-1U: copied unmodified from Espressif's official KiCad library
(github.com/espressif/kicad-libraries, footprints/Espressif.pretty, CC-BY-SA 4.0 with Espressif's design exception),
because it matches the datasheet land pattern (ESP32-C3-MINI-1 & MINI-1U Datasheet v2.2, Figure 11-2, p39):
perimeter pads 0.4 x 0.8 at 0.8 pitch, four 0.7 corner pads, nine 1.45 mm centre GND pads (pin 49) at 1.975 pitch.
The LCSC footprint (C2911374) enlarges the perimeter pads to 0.5 x 1.0 and was not used.

Usage: gen_radio_footprints.py OUT_DIR/radio.pretty ESPRESSIF_KICAD_MOD
"""
import os, shutil, sys, uuid

TI_NAME = 'TI_DLA0010A_VSON-HR-10_2x3mm_P0.5mm'
H = 0.25
LEFT = [(str(n), -0.90, -1.0 + 0.5 * (n - 1), 0.60) for n in range(1, 6)]
RIGHT = [('10', 0.75, -1.0, 0.90), ('9', 0.75, -0.5, 0.90), ('8', 0.55, 0.0, 1.30),
         ('7', 0.75, 0.5, 0.90), ('6', 0.75, 1.0, 0.90)]


def ti_footprint():
    u = lambda: str(uuid.uuid4())
    pads = '\n'.join(
        f'\t(pad "{n}" smd roundrect (at {x:g} {y:g}) (size {w:g} {H:g}) (layers "F.Cu" "F.Paste" "F.Mask") '
        f'(roundrect_rratio {0.05 / H:.3f}) (solder_mask_margin 0.05) (uuid "{u()}"))'
        for n, x, y, w in LEFT + RIGHT)
    body = [(-1.0, -1.5), (1.0, -1.5), (1.0, 1.5), (-1.0, 1.5)]
    lines = '\n'.join(f'\t(fp_line (start {a[0]:g} {a[1]:g}) (end {b[0]:g} {b[1]:g}) (stroke (width 0.1) (type solid)) (layer "F.Fab") (uuid "{u()}"))'
                      for a, b in zip(body, body[1:] + body[:1]))
    return f'''(footprint "{TI_NAME}"
\t(version 20241229)
\t(generator "gen_radio_footprints")
\t(layer "F.Cu")
\t(descr "TI DLA0010A VSON-HR 10-pin 2x3 mm (TPS63802), land pattern per SLVSEU9D p36, generated by hw/rev-b/tools/gen_radio_footprints.py")
\t(tags "VSON-HR DLA0010A TPS63802")
\t(property "Reference" "REF**" (at 0 -2.4 0) (layer "F.SilkS") (uuid "{u()}") (effects (font (size 0.8 0.8) (thickness 0.12))))
\t(property "Value" "{TI_NAME}" (at 0 2.4 0) (layer "F.Fab") (uuid "{u()}") (effects (font (size 0.8 0.8) (thickness 0.12))))
\t(attr smd)
{lines}
\t(fp_circle (center -1.45 -1.0) (end -1.35 -1.0) (stroke (width 0.2) (type solid)) (fill solid) (layer "F.SilkS") (uuid "{u()}"))
\t(fp_rect (start -1.45 -1.75) (end 1.45 1.75) (stroke (width 0.05) (type solid)) (fill none) (layer "F.CrtYd") (uuid "{u()}"))
{pads}
)
'''


def main(out_dir, esp_src):
    os.makedirs(out_dir, exist_ok=True)
    open(os.path.join(out_dir, TI_NAME + '.kicad_mod'), 'w').write(ti_footprint())
    shutil.copyfile(esp_src, os.path.join(out_dir, 'ESP32-C3-MINI-1U.kicad_mod'))
    print(f'wrote {out_dir}: {TI_NAME}, ESP32-C3-MINI-1U')


if __name__ == '__main__':
    main(*sys.argv[1:3])
